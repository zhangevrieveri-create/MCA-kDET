parse_n <- function(n, k) {
  v <- as.integer(strsplit(as.character(n), "[,;: ]+")[[1L]])
  if (length(v) == 1L) v <- rep(v, k)
  if (length(v) != k) stop("length of n must be 1 or k")
  v
}

# "patience=30;lr=0.003" -> NN_DEFAULT with these entries replaced
nn_config <- function(spec) {
  cfg <- NN_DEFAULT
  if (is.na(spec) || !nzchar(spec)) return(cfg)
  for (kv in strsplit(strsplit(spec, ";", fixed = TRUE)[[1L]], "=", fixed = TRUE)) {
    v <- kv[2L]
    cfg[[kv[1L]]] <- if (v %in% c("TRUE", "FALSE")) as.logical(v)
                     else if (grepl("-", v)) as.integer(strsplit(v, "-")[[1L]])
                     else as.numeric(v)
  }
  cfg
}

one_rep <- function(cell, r) {
  # E8 (GARCH null, R/garch_ext.R) has its own replication; every other model
  # takes the path below unchanged
  if (identical(cell$model, "GARCH")) return(one_rep_garch(cell, r))
  seed <- as.integer(cell$seed0) + as.integer(r)
  set.seed(seed)
  k <- as.integer(cell$k)
  nvec <- parse_n(cell$n, k)
  par <- list(cA = cell$cA, cB = cell$cB, sC = cell$sC, cE = cell$cE)
  groups <- strsplit(cell$groups, ",", fixed = TRUE)[[1L]]
  B <- as.integer(cell$B)
  nn_cfg <- nn_config(if (is.null(cell$nn)) "" else cell$nn)
  lib <- parse_lib(cell$lib)                       # default "l1,nn"
  libsets <- parse_libsets(cell$libsets, lib)      # default: one set = lib
  t_all <- proc.time()[["elapsed"]]
  # S1-S3 (R/models_s.R) are generated by gen_any(); A-E go through gen_data() unchanged
  data <- gen_any(cell$model, cell$beta, nvec, as.integer(cell$d), par)
  # E10 (G1, 1 Nov 2026): rotated models, R/rotation.R; Q has its own seed and
  # the random-number state is restored, so nothing else changes
  if (!is.null(cell$rot) && !is.na(cell$rot) && as.integer(cell$rot) > 0L)
    data <- rotate_data(data, as.integer(cell$rot))

  row <- list(exp = cell$exp, cell = cell$cell, rep = r, seed = seed, err = "")
  cls_groups <- intersect(groups, c("ovr", "shared", "pair"))
  if (length(cls_groups)) {
    nsplit <- max(1L, as.integer(cell$nsplit))
    p_ms <- numeric(nsplit)
    for (s in seq_len(nsplit)) {
      sp <- split_data(data, cell$tau)
      sc <- fit_scores(sp, if (s == 1L) cls_groups else "ovr", nn_cfg = nn_cfg, lib = lib)
      ct <- classifier_tests(sc, B, libsets = libsets)
      if (s == 1L) {
        row <- c(row, ct$p, ct$diag, setNames(sc$tm, paste0("t_", names(sc$tm))))
      }
      if (!is.null(ct$p$mca)) p_ms[s] <- ct$p$mca
    }
    if (nsplit > 1L) {
      row$mca_ms_med  <- min(1, 2 * median(p_ms))   # Meinshausen et al. (2009)
      row$mca_ms_mean <- min(1, 2 * mean(p_ms))     # Vovk and Wang (2020)
    }
  }
  comp_groups <- intersect(groups, c("dist", "schott", "comp2", "comp2ovr", "songchen"))
  if (length(comp_groups)) {
    ctp <- competitor_tests(data, B, comp_groups)
    row <- c(row, ctp$p, setNames(ctp$tm, paste0("t_", names(ctp$tm))))
  }
  row$t_total <- proc.time()[["elapsed"]] - t_all
  row
}

# A replication is retried (same seed, hence the same data, split and
# permutations) when R itself fails, e.g. on a sporadic lazy-load error;
# retrying does not change the result of a replication that succeeds.
safe_rep <- function(cell, r, tries = 3L) {
  msgs <- character(0)
  for (a in seq_len(tries)) {
    res <- tryCatch(one_rep(cell, r), error = function(e) conditionMessage(e))
    if (is.list(res)) { res$retries <- a - 1L; return(res) }
    msgs <- c(msgs, res)
  }
  list(exp = cell$exp, cell = cell$cell, rep = r,
       seed = as.integer(cell$seed0) + as.integer(r), retries = tries,
       err = paste(unique(msgs), collapse = " | "))
}

rows_to_df <- function(rows) {
  keys <- unique(unlist(lapply(rows, names)))
  cols <- lapply(keys, function(kk) {
    v <- lapply(rows, function(x) {
      z <- x[[kk]]
      if (is.null(z) || length(z) == 0L) NA else unname(unlist(z))[1L]
    })
    unlist(v)
  })
  names(cols) <- keys
  data.frame(cols, stringsAsFactors = FALSE, check.names = FALSE)
}

# Runs replications 1..reps of a cell in chunks; every chunk is written to
# disk at once, so an interrupted run resumes from the last finished chunk.
# progress (optional): function(n, new) called after every chunk with the
# number of replications in it; new = FALSE for chunks found on disk
run_cell <- function(cell, reps, cl = NULL, outdir = "results", chunk = 50L,
                     log = message, progress = NULL) {
  dir.create(file.path(outdir, cell$exp), recursive = TRUE, showWarnings = FALSE)
  starts <- seq(1L, reps, by = chunk)
  for (s in starts) {
    e <- min(reps, s + chunk - 1L)
    f <- file.path(outdir, cell$exp, sprintf("%s__r%05d-%05d.csv", cell$cell, s, e))
    if (file.exists(f)) { if (!is.null(progress)) progress(e - s + 1L, FALSE); next }
    t0 <- proc.time()[["elapsed"]]
    rr <- s:e
    rows <- if (is.null(cl)) lapply(rr, function(r) safe_rep(cell, r))
            else parallel::parLapplyLB(cl, rr, function(r, cell) safe_rep(cell, r), cell = cell)
    df <- tryCatch({
      cpart <- cell[setdiff(names(cell), c("exp", "cell"))]
      cpart <- lapply(cpart, function(v) rep(unname(unlist(v))[1L], length(rows)))
      cbind(data.frame(cpart, stringsAsFactors = FALSE, check.names = FALSE), rows_to_df(rows))
    }, error = function(e) {
      saveRDS(list(cell = cell, rows = rows), paste0(f, ".debug.rds"))
      # no str()/capture.output() here: they may trigger lazy loading, which is
      # what fails on this machine (CLAUDE.md)
      log(sprintf("  !! could not assemble %s: %s (rows saved to .debug.rds)",
                  basename(f), conditionMessage(e)))
      NULL
    })
    if (is.null(df)) { if (!is.null(progress)) progress(e - s + 1L, TRUE); next }
    write.csv(df, paste0(f, ".tmp"), row.names = FALSE)
    file.rename(paste0(f, ".tmp"), f)
    nerr <- sum(df$err != "")
    log(sprintf("[%s] %s reps %d-%d done in %.0fs%s", format(Sys.time(), "%H:%M:%S"),
                cell$cell, s, e, proc.time()[["elapsed"]] - t0,
                if (nerr) sprintf("  (%d errors: %s)", nerr, df$err[df$err != ""][1L]) else ""))
    if (!is.null(progress)) progress(e - s + 1L, TRUE)
  }
  invisible(TRUE)
}

make_cluster <- function(cores, srcdir) {
  cl <- parallel::makeCluster(cores)
  parallel::clusterExport(cl, "srcdir", envir = environment())
  parallel::clusterEvalQ(cl, {
    Sys.setenv(OMP_NUM_THREADS = "1", OPENBLAS_NUM_THREADS = "1", MKL_NUM_THREADS = "1")
    SRC_DIR <- srcdir           # models_s.R reads R/calib_params_s.R from here
    for (f in c("models.R", "learners.R", "learners_lib.R", "tests.R", "sim.R", "garch_ext.R",
                "competitors2.R", "rotation.R", "learners_lib2.R", "models_s.R"))
      source(file.path(srcdir, f))
    suppressPackageStartupMessages(requireNamespace("glmnet"))
    # ranger is loaded only if installed; install it beforehand, never inside
    # the cluster (see CLAUDE.md, lazy-load corruption)
    suppressPackageStartupMessages(requireNamespace("ranger", quietly = TRUE))
    suppressPackageStartupMessages(requireNamespace("gTestsMulti", quietly = TRUE))
    NULL
  })
  cl
}
